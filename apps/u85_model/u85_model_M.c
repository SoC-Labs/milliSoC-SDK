/*
 * SRAM layout (64 KiB at MODEL_SRAM_BASE):
 *
 *   0x0000  image copy            (MODEL_RUN_FROM_FLASH == 0 only)
 *   0x8000  arena: feature maps, scratch and I/O
 *   0xC000  fast scratch          (only used if Vela allocates one)
 *
 * The offsets are chosen for the largest model that fits the current 64 KiB
 * SRAM: an image of up to 32 KiB plus a 16 KiB arena.  hello_world_int8 uses
 * 1.7 KiB + 64 B of that and micro_speech_int8 uses 24.7 KiB + 14.1 KiB, so
 * both fit with room for a fast-scratch buffer.  The runtime checks the
 * header against these limits and reports a clear FAIL if a model is bigger;
 * raise them (and the SRAM size) for a larger model.
 */
#ifndef MODEL_COPY_OFFSET
#define MODEL_COPY_OFFSET       0x0000UL
#endif
#ifndef MODEL_ARENA_OFFSET
#define MODEL_ARENA_OFFSET      0x8000UL
#endif
#ifndef MODEL_ARENA_SIZE
#define MODEL_ARENA_SIZE        0x4000UL
#endif

#ifndef MODEL_BENCHMARK_REPEATS
#define MODEL_BENCHMARK_REPEATS 100U
#endif
/* MACs per inference; 0 means "read it from the model image header". */
#ifndef MODEL_MACS_FALLBACK
#define MODEL_MACS_FALLBACK     0U
#endif
#ifndef MODEL_MAC_UNITS
#define MODEL_MAC_UNITS         128U
#endif
#ifndef MODEL_NPU_CLOCK_HZ
#define MODEL_NPU_CLOCK_HZ      8000000UL
#endif
#ifndef MODEL_HOST_CLOCK_HZ
#define MODEL_HOST_CLOCK_HZ     8000000UL
#endif

#define U85_POLL_TIMEOUT        1000000UL

